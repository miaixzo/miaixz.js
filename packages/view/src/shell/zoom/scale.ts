/**
 * Restricts a preview scale to an inclusive range.
 *
 * @param scale - Candidate scale.
 * @param minimum - Inclusive lower boundary.
 * @param maximum - Inclusive upper boundary.
 * @returns Bounded scale.
 */
export function clampScale(scale: number, minimum: number, maximum: number): number {
  return Math.min(Math.max(scale, minimum), maximum);
}
